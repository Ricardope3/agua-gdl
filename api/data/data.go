// Package data embeds SIAPA's rotation map, colonia list and weekly schedule, and INE's other colonias.
package data

import _ "embed"

// Zonas is SIAPA's rotation map: its colonia outlines with the zones it gives each one, and
// its seven zone polygons. It is a copy of web/colonias_siapa.topo.json, which
// pipelines/siapa_mapa.py writes to both places (go:embed can't reach web/).
//
//go:embed colonias_siapa.topo.json
var Zonas []byte

//go:embed colonias.json
var Colonias []byte

//go:embed rotation.json
var Rotation []byte

// OtrasColonias are the colonias in INE's cartography or on SIAPA's map that aren't on
// SIAPA's list, with their zones on SIAPA's map, generated by pipelines/colonias_poligonos.py.
//
//go:embed otras_colonias.json
var OtrasColonias []byte

// ColoniasMapa lists each colonia on /reportes once as [name, municipio, postal code, zones],
// generated from web/colonias_siapa.topo.json by pipelines/mapa_colonias.py.
//
//go:embed colonias_mapa.json
var ColoniasMapa []byte
